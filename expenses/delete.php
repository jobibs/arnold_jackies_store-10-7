<?php

require_once "../config/database.php";
require_once "../config/auth.php";

require_login();


/*
|--------------------------------------------------------------------------
| Only accept POST requests
|--------------------------------------------------------------------------
*/

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {

    header("Location: index.php");
    exit;
}


/*
|--------------------------------------------------------------------------
| Get Expense ID
|--------------------------------------------------------------------------
*/

$id = (int)($_POST['id'] ?? 0);

if ($id <= 0) {

    header("Location: index.php");
    exit;
}


/*
|--------------------------------------------------------------------------
| Delete Expense
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    DELETE FROM expenses
    WHERE id = ?
    LIMIT 1
");

$stmt->execute([$id]);


/*
|--------------------------------------------------------------------------
| Return to Expenses
|--------------------------------------------------------------------------
*/

header("Location: index.php?deleted=1");
exit;
